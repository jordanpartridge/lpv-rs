pub fn validate(
    args: &ValidateArgs,
    ctx: &mut Ctx,
) -> Result<(i32, Option<ValidateReport>), LpvError> {
    let mut report = ValidateReport {
        tool: "lpv-rs",
        version: env!("CARGO_PKG_VERSION"),
        command: "validate",
        strategy: "classic",
        ..Default::default()
    };
    let mut a = Analyser::new(&ctx.cwd);
    let code = validate_inner(args, ctx, &mut a, &mut report)?;
    if ctx.format != Format::Json {
        return Ok((code, None));
    }
    report.exit_code = code;
    report.valid = code == 0;
    report.directory = realpath(&ctx.cwd, &a.directory);
    let present = a.has_gitattributes_file();
    report.gitattributes_present = present;
    report.gitattributes_path = present.then(|| {
        a.dir_path()
            .join(".gitattributes")
            .to_string_lossy()
            .into_owned()
    });
    if a.file_uses_negated() {
        report.strategy = "negated";
    }
    if a.dir_path().is_dir() && report.strategy == "classic" {
        let expected = a.collect_expected();
        let actual = a.present(true);
        let mut missing: Vec<String> = expected
            .iter()
            .filter(|e| !actual.contains(e))
            .cloned()
            .collect();
        if !present {
            missing.push(".gitattributes".to_string());
            php::sort_case(&mut missing);
        }
        report.missing_export_ignores = missing;
        report.unexpected_export_ignores = actual
            .iter()
            .filter(|e| !expected.contains(e))
            .cloned()
            .collect();
        report.stale_export_ignores = a.stale_entries();
        if report.expected_gitattributes_content.is_none() && code != 0 {
            report.expected_gitattributes_content = a.expected_content(Flavour::Classic).ok();
        }
    }
    Ok((code, Some(report)))
}

fn validate_inner(
    args: &ValidateArgs,
    ctx: &mut Ctx,
    a: &mut Analyser,
    report: &mut ValidateReport,
) -> Result<i32, LpvError> {
    const NAME: &str = "validate";
    let cwd_str = ctx.cwd.to_string_lossy().into_owned();
    let directory = args.directory.clone().unwrap_or_else(|| cwd_str.clone());
    let agentic = ctx.agentic;

    if directory != cwd_str && a.set_directory(&directory).is_err() {
        let warning = format!(
            "Warning: The provided directory '{directory}' does not exist or is not a directory."
        );
        report.message = warning.clone();
        if agentic {
            ctx.agentic_output(NAME, false, &warning, vec![]);
        } else {
            ctx.out.writeln(&format!("<error>{warning}</error>"));
        }
        ctx.out
            .debug(&format!("Directory {directory} doesn't exist."));
        return Ok(1);
    }

    let opts = GenerationOptions {
        glob: &args.glob,
        keep_glob_pattern: if args.keep_glob_pattern {
            "1".to_string()
        } else {
            String::new()
        },
        align: false,
    };

    if args.stdin_input {
        let mut input = Vec::new();
        std::io::Read::read_to_end(&mut std::io::stdin(), &mut input)
            .map_err(|e| LpvError::Io(format!("cannot read standard input: {e}")))?;
        let input = String::from_utf8_lossy(&input).into_owned();
        let contents = php::trim(&input);
        if !contents.find("export-ignore").is_some_and(|p| p > 0) {
            let warning =
                "Warning: The provided input stream seems to be no .gitattributes content.";
            report.message = warning.to_string();
            if agentic {
                ctx.agentic_output(NAME, false, warning, vec![]);
            } else {
                ctx.out.writeln(&format!("<error>{warning}</error>"));
            }
            return Ok(1);
        }
        if !apply_generation_options(ctx, a, &opts) {
            return Ok(1);
        }
        ctx.out
            .verbose("+ Validating .gitattributes content from STDIN.");
        if a.has_complete_from_string(contents) {
            let msg = "The provided .gitattributes content is considered valid.";
            report.message = msg.to_string();
            if agentic {
                ctx.agentic_output(NAME, true, msg, vec![("valid", PhpJson::Bool(true))]);
            } else {
                ctx.out.writeln(
                    "The provided .gitattributes content is considered <info>valid</info>.",
                );
            }
            return Ok(0);
        }
        report.message = "The provided .gitattributes content is considered invalid.".to_string();
        if agentic {
            ctx.agentic_output(
                NAME,
                false,
                "The provided .gitattributes content is considered invalid.",
                vec![("valid", PhpJson::Bool(false))],
            );
        } else {
            ctx.out
                .writeln("The provided .gitattributes file is considered <error>invalid</error>.");
        }
        return Ok(1);
    }

    ctx.out.verbose(&format!(
        "+ Scanning directory {}.",
        realpath(&ctx.cwd, &directory)
    ));

    if !apply_generation_options(ctx, a, &opts) {
        return Ok(1);
    }

    if args.report_impact {
        return Err(LpvError::Unsupported(
            "--report-impact (distribution impact report) is not ported to lpv-rs yet.".to_string(),
        ));
    }

    let glob = &args.glob;
    if glob.enforce_strict_order && !glob.sort_from_directories_to_files {
        ctx.out.verbose("+ Enforcing strict order comparison.");
        a.enable_strict_order();
    }
    if glob.sort_from_directories_to_files {
        ctx.out.verbose("+ Sorting from files to directories.");
        a.enable_sort_dirs_to_files();
    }
    if args.report_stale_export_ignores {
        ctx.out
            .verbose("+ Enforcing stale export ignores comparison.");
        a.enable_stale();
    }
    if args.enforce_alignment {
        ctx.out.verbose("+ Enforcing alignment comparison.");
        a.enable_strict_alignment();
    }
    keep_license_option(ctx, a, glob.keep_license);
    if glob.keep_readme {
        ctx.out.verbose("+ Keeping the README file.");
        a.enable_keep_readme();
    }
    if !select_glob(ctx, a, glob, false) {
        return Ok(1);
    }

    ctx.out.verbose(&format!(
        "+ Checking .gitattributes file existence in {}.",
        realpath(&ctx.cwd, &directory)
    ));

    if !a.has_gitattributes_file() {
        let warning = format!(
            "Warning: There is no .gitattributes file present in {}.",
            a.directory
        );
        report.message = warning.clone();
        if !agentic {
            ctx.out.write(&format!("<error>{warning}</error>"));
        }
        ctx.out
            .verbose("+ Getting expected .gitattributes file content.");
        let expected = a.expected_content(Flavour::Classic)?;
        if !expected.is_empty() {
            ctx.out.verbose("+ Suggesting .gitattributes file content.");
            report.expected_gitattributes_content = Some(expected.clone());
            if agentic {
                ctx.agentic_output(
                    NAME,
                    false,
                    &warning,
                    vec![
                        ("valid", PhpJson::Bool(false)),
                        ("expected_gitattributes_content", PhpJson::Str(expected)),
                    ],
                );
            } else {
                ctx.out.writeln(&format!(
                    "\n\nWould expect the following .gitattributes file content:\n<info>{expected}</info>\nUse the <info>create</info> command to create a .gitattributes file with the shown content."
                ));
            }
            return Ok(1);
        }
        if agentic {
            ctx.agentic_output(
                NAME,
                false,
                "Unable to resolve expected .gitattributes content.",
                vec![],
            );
        } else {
            ctx.out
                .writeln("\n\n<info>Unable to resolve expected .gitattributes content.</info>");
        }
        return Ok(1);
    }

    if args.validate_git_archive {
        ctx.out.verbose("+ Validating Git archive.");
        report.archive_validated = true;
        let keep_license = a.is_keep_license_enabled();
        let expected = a.collect_expected();
        let cwd = ctx.cwd.clone();
        return match archive::validate(&cwd, &expected, keep_license) {
            Ok(check) if check.found_unexpected.is_empty() => {
                let msg = "The archive file of the current HEAD is considered lean.";
                report.message = msg.to_string();
                report.archive_leaks = Some(Vec::new());
                if agentic {
                    ctx.agentic_output(
                        NAME,
                        true,
                        msg,
                        vec![("archive_valid", PhpJson::Bool(true))],
                    );
                } else {
                    ctx.out.writeln(&format!("<info>{msg}</info>"));
                }
                Ok(0)
            }
            Ok(check) => {
                let found = check.found_unexpected;
                let msg = "The archive file of the current HEAD is not considered lean.";
                report.message = msg.to_string();
                report.archive_leaks = Some(found.clone());
                if agentic {
                    ctx.agentic_output(
                        NAME,
                        false,
                        msg,
                        vec![
                            ("archive_valid", PhpJson::Bool(false)),
                            ("unexpected_artifacts", PhpJson::List(found)),
                        ],
                    );
                    return Ok(1);
                }
                let label = if found.len() == 1 {
                    "artifact"
                } else {
                    "artifacts"
                };
                ctx.out.writeln(&format!(
                    "<error>{msg}</error>\n\nSeems like the following {label} slipped in:<info>\n{}</info>\n",
                    found.join("\n")
                ));
                Ok(1)
            }
            Err(LpvError::NoLicenseFilePresent) => {
                let msg = "The archive file of the current HEAD is considered invalid due to a missing license file.";
                report.message = msg.to_string();
                ctx.out.debug("No license file present in archive.");
                if agentic {
                    ctx.agentic_output(NAME, false, msg, vec![]);
                    return Ok(1);
                }
                ctx.out.writeln(&format!("<error>{msg}</error>\n"));
                Ok(1)
            }
            Err(other) => Err(other),
        };
    }

    ctx.out.verbose("+ Analysing the .gitattributes content.");

    if !a.has_complete() {
        if a.file_uses_negated() {
            let msg = "The present .gitattributes file with negated export-ignore directives is considered <error>invalid</error>.";
            report.message = strip(msg);
            if agentic {
                ctx.agentic_output(
                    NAME,
                    false,
                    &strip(msg),
                    vec![("valid", PhpJson::Bool(false))],
                );
            } else {
                ctx.out.writeln(msg);
            }
            return Ok(1);
        }
        ctx.out
            .verbose("+ Gathering expected .gitattributes content.");
        let mut expected = a.expected_content(Flavour::Classic)?;
        let present = a.present_content();
        if expected == present {
            report.message = "The present .gitattributes file is considered valid.".to_string();
            ctx.out
                .writeln("The present .gitattributes file is considered <info>valid</info>.");
            return Ok(0);
        }
        report.expected_gitattributes_content = Some(expected.clone());
        if args.diff {
            expected = diff::unified_diff(&present, &expected);
        }
        report.message = "The present .gitattributes file is considered invalid.".to_string();
        if agentic {
            ctx.agentic_output(
                NAME,
                false,
                "The present .gitattributes file is considered invalid.",
                vec![
                    ("valid", PhpJson::Bool(false)),
                    ("expected_gitattributes_content", PhpJson::Str(expected)),
                ],
            );
        } else {
            ctx.out.writeln(&format!(
                "The present .gitattributes file is considered <error>invalid</error>.\n\nWould expect the following .gitattributes file content:\n<info>{expected}</info>"
            ));
        }
        return Ok(1);
    }

    let mut warnings: Vec<String> = Vec::new();
    if a.has_preceding_slashes() {
        ctx.out
            .verbose("+ Checking for preceding slashes in export-ignore statements.");
        warnings.push(
            "Warning: At least one export-ignore pattern has a leading '/', which is considered as a smell."
                .to_string(),
        );
    }
    if !a.has_text_autoconfiguration() {
        ctx.out.verbose("+ Checking for text auto configuration.");
        warnings
            .push("Warning: Missing a text auto configuration. Consider adding one.".to_string());
    }
    report.message = "The present .gitattributes file is considered valid.".to_string();
    report.warnings = warnings.clone();
    if agentic {
        let mut extra = vec![("valid", PhpJson::Bool(true))];
        if !warnings.is_empty() {
            extra.push(("warnings", PhpJson::List(warnings)));
        }
        ctx.agentic_output(
            NAME,
            true,
            "The present .gitattributes file is considered valid.",
            extra,
        );
    } else {
        ctx.out
            .writeln("The present .gitattributes file is considered <info>valid</info>.");
        for w in &warnings {
            ctx.out.writeln(&format!("<error>{w}</error>"));
        }
    }
    Ok(0)
}

