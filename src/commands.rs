pub const GENERATED_HEADER: &str = "# This file was generated by the lean package validator (http://git.io/lean-package-validator).";
pub const MODIFIED_HEADER: &str = "# This file was partly modified by the lean package validator (http://git.io/lean-package-validator).";

pub struct Ctx {
    pub out: Output,
    pub cwd: PathBuf,
    /// lpv's agent mode (JSON via `writeAgenticOutput`).
    pub agentic: bool,
    pub format: Format,
}

impl Ctx {
    fn agentic_output(
        &mut self,
        command: &str,
        success: bool,
        message: &str,
        extra: Vec<(&str, PhpJson)>,
    ) {
        let mut entries: Vec<(&str, PhpJson)> = vec![
            ("command", PhpJson::Str(command.to_string())),
            (
                "status",
                PhpJson::Str(if success { "success" } else { "failure" }.to_string()),
            ),
            ("message", PhpJson::Str(message.to_string())),
        ];
        entries.extend(extra);
        let json = php::php_json_encode(&entries);
        self.out.raw_line(&json);
    }
}

/// Generation options shared by all commands (`GeneratesGitattributesOptions`).
pub struct GenerationOptions<'a> {
    pub glob: &'a GlobArgs,
    /// `(string) $input->getOption('keep-glob-pattern')`.
    pub keep_glob_pattern: String,
    pub align: bool,
}

fn default_lpv_file(cwd: &Path) -> String {
    format!("{}/.lpv", cwd.to_string_lossy())
}

fn php_truthy(s: &str) -> bool {
    !s.is_empty() && s != "0"
}

/// The strerror() part of an I/O error, without Rust's " (os error N)".
fn io_reason(e: &std::io::Error) -> String {
    let text = e.to_string();
    match text.find(" (os error") {
        Some(pos) => text[..pos].to_string(),
        None => text,
    }
}

/// Write the generated `.gitattributes`, refusing to follow a symlink.
///
/// `std::fs::write` follows symlinks, so a `.gitattributes` link (dangling or
/// not) would write the generated content to wherever it points. Only a
/// regular file, or no file, is written.
fn write_gitattributes(fs_path: &Path, content: &str) -> std::io::Result<()> {
    if let Ok(meta) = std::fs::symlink_metadata(fs_path)
        && meta.file_type().is_symlink()
    {
        return Err(std::io::Error::other("refusing to write through a symlink"));
    }
    std::fs::write(fs_path, content)
}

fn realpath(cwd: &Path, directory: &str) -> String {
    std::fs::canonicalize(cwd.join(directory))
        .map(|p| p.to_string_lossy().into_owned())
        .unwrap_or_default()
}

/// The glob selection block: explicit pattern -> glob file -> preset.
fn select_glob(ctx: &mut Ctx, a: &mut Analyser, glob: &GlobArgs, announce_preset: bool) -> bool {
    let default_file = default_lpv_file(&ctx.cwd);
    let glob_pattern_file = glob
        .glob_pattern_file
        .clone()
        .unwrap_or_else(|| default_file.clone());
    let chosen_preset = glob.preset.clone().unwrap_or_else(|| "Php".to_string());
    let default_present = ctx.cwd.join(".lpv").exists();

    if let Some(pattern) = glob
        .glob_pattern
        .as_deref()
        .filter(|p| p.is_empty() || *p != "0")
    {
        ctx.out
            .verbose(&format!("+ Using glob pattern <info>{pattern}</info>."));
        if a.set_glob_pattern(pattern).is_err() {
            ctx.out.writeln(&format!(
                "<error>Warning: The provided glob pattern '{pattern}' is considered invalid.</error>"
            ));
            ctx.out.debug("");
            return false;
        }
    } else if glob_pattern_file != default_file || default_present {
        let mut result = Ok(());
        if default_present {
            result = a.set_glob_pattern_from_file(&glob_pattern_file);
        }
        if result.is_ok() && php_truthy(&glob_pattern_file) {
            ctx.out.verbose(&format!(
                "+ Using {} file as glob pattern input.",
                php::basename(&glob_pattern_file)
            ));
            result = a.set_glob_pattern_from_file(&glob_pattern_file);
        }
        match result {
            Ok(()) => {}
            Err(GlobFileError::NonExistent) => {
                ctx.out.writeln(&format!(
                    "<error>Warning: The provided glob pattern file '{glob_pattern_file}' doesn't exist.</error>"
                ));
                ctx.out.debug(&format!(
                    "Glob pattern file {glob_pattern_file} doesn't exist."
                ));
                return false;
            }
            Err(GlobFileError::Invalid) => {
                ctx.out.writeln(&format!(
                    "<error>Warning: The provided glob pattern file '{glob_pattern_file}' is considered invalid.</error>"
                ));
                ctx.out.debug(&format!(
                    "Glob pattern file '{glob_pattern_file}' is invalid."
                ));
                return false;
            }
        }
    } else if php_truthy(&chosen_preset) {
        if announce_preset {
            ctx.out
                .verbose(&format!("+ Using the {chosen_preset} language preset."));
        }
        if a.set_glob_pattern_from_preset(&chosen_preset).is_err() {
            ctx.out.writeln(&format!(
                "<error>Warning: The chosen language preset {chosen_preset} is not available. Maybe contribute it!?</error>"
            ));
            return false;
        }
    }
    true
}

fn keep_license_option(ctx: &mut Ctx, a: &mut Analyser, keep_license: bool) {
    if keep_license {
        ctx.out.verbose("+ Keeping the license file.");
        a.enable_keep_license();
    } else if a.is_keep_license_enabled() {
        ctx.out
            .verbose("+ Keeping the license file. (MIT license auto-detected)");
    }
}

/// `applyGenerationOptions()`.
fn apply_generation_options(ctx: &mut Ctx, a: &mut Analyser, opts: &GenerationOptions<'_>) -> bool {
    let glob = opts.glob;
    if glob.enforce_strict_order && !glob.sort_from_directories_to_files {
        ctx.out.verbose("+ Enforcing strict order comparison.");
        a.enable_strict_order();
    }
    if glob.sort_from_directories_to_files {
        ctx.out.verbose("+ Sorting from files to directories.");
        a.enable_sort_dirs_to_files();
    }
    keep_license_option(ctx, a, glob.keep_license);
    if glob.keep_readme {
        ctx.out.verbose("+ Keeping the README file.");
        a.enable_keep_readme();
    }
    let keep = opts.keep_glob_pattern.as_str();
    if !keep.is_empty() {
        ctx.out.verbose(&format!(
            "+ Keeping files matching the glob pattern <info>{keep}</info>."
        ));
        if a.set_keep_glob_pattern(keep).is_err() {
            ctx.out.writeln(&format!(
                "<error>Warning: The provided glob pattern '{keep}' is considered invalid.</error>"
            ));
            ctx.out.debug("");
            return false;
        }
    }
    if opts.align {
        ctx.out.verbose("+ Aligning the export-ignores.");
        a.enable_align();
    }
    select_glob(ctx, a, glob, true)
}

